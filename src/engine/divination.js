function hash32(t) {
  let h = 2166136261;
  for (let i = 0; i < t.length; i++) { h ^= t.charCodeAt(i); h = (h * 16777619) >>> 0; }
  return h >>> 0;
}
function pad(n) { return n < 10 ? '0' + n : '' + n; }

export function pickDay(al) {
  const d = al || {};
  const seed = hash32(String(d.gzYear || '') + String(d.gzMonth || '') + String(d.gzDay || '') +
    String((d.hourNow && d.hourNow.name) || '') + String(d.y || '') + pad(d.m || 0) + pad(d.d || 0));
  return seed % Q_GUA.length;
}

export function pickRandom() { return Math.floor(Math.random() * Q_GUA.length); }

/**
 * 抽签
 * @param {string} mode 'day' 按日辰定签 | 'random' 随手一抽
 * @param {object} al 今日黄历
 * @returns {gua}
 */
export function draw(mode, al) {
  const i = (mode === 'day') ? pickDay(al) : pickRandom();
  return { i, name: Q_GUA[i][0], lv: Q_GUA[i][1], brief: Q_GUA[i][2], mode };
}

